"""SQLite and PostgreSQL persistence for scan history and reports."""

from __future__ import annotations

import importlib
import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


SCHEMA = """
CREATE TABLE IF NOT EXISTS scans (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    target TEXT NOT NULL,
    final_url TEXT,
    scanned_at TEXT NOT NULL,
    status TEXT NOT NULL,
    score INTEGER NOT NULL,
    summary TEXT NOT NULL,
    response_status INTEGER,
    response_size INTEGER,
    results_json TEXT NOT NULL,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    contact TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS generated_reports (
    scan_id INTEGER PRIMARY KEY,
    pdf BLOB NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (scan_id) REFERENCES scans(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_scans_scanned_at ON scans(scanned_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
"""

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target TEXT NOT NULL,
    final_url TEXT,
    scanned_at TEXT NOT NULL,
    status TEXT NOT NULL,
    score INTEGER NOT NULL,
    summary TEXT NOT NULL,
    response_status INTEGER,
    response_size INTEGER,
    results_json TEXT NOT NULL,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    contact TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS generated_reports (
    scan_id BIGINT PRIMARY KEY,
    pdf BYTEA NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (scan_id) REFERENCES scans(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_scans_scanned_at ON scans(scanned_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
"""

MIGRATIONS = (
    "ALTER TABLE scans ADD COLUMN final_url TEXT",
    "ALTER TABLE scans ADD COLUMN response_status INTEGER",
    "ALTER TABLE scans ADD COLUMN response_size INTEGER",
)

POSTGRES_MIGRATIONS = (
    "ALTER TABLE scans ADD COLUMN IF NOT EXISTS final_url TEXT",
    "ALTER TABLE scans ADD COLUMN IF NOT EXISTS response_status INTEGER",
    "ALTER TABLE scans ADD COLUMN IF NOT EXISTS response_size INTEGER",
)


class ScanStore:
    """Persist scanner records in SQLite locally or PostgreSQL when configured."""

    def __init__(self, database_path: str | Path):
        location = str(database_path)
        self.is_postgres = location.startswith(("postgres://", "postgresql://"))
        self.database_location = (
            location.replace("postgres://", "postgresql://", 1)
            if location.startswith("postgres://")
            else location
        )
        if "://" in location and not self.is_postgres:
            raise ValueError("DATABASE_URL must be a PostgreSQL connection URL.")
        if not self.is_postgres:
            Path(location).parent.mkdir(parents=True, exist_ok=True)
        self._initialize()

    def _connect(self) -> Any:
        if self.is_postgres:
            try:
                psycopg = importlib.import_module("psycopg")
                dict_row = importlib.import_module("psycopg.rows").dict_row
            except ImportError as exc:
                raise RuntimeError(
                    "PostgreSQL storage requires the psycopg package."
                ) from exc
            return psycopg.connect(
                self.database_location,
                connect_timeout=10,
                row_factory=dict_row,
            )

        connection = sqlite3.connect(self.database_location, timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute("PRAGMA journal_mode = WAL")
        return connection

    def _execute(self, connection: Any, query: str, parameters: tuple = ()) -> Any:
        if self.is_postgres:
            query = query.replace("?", "%s")
        return connection.execute(query, parameters)

    def _initialize(self) -> None:
        with self._connect() as connection:
            if self.is_postgres:
                for statement in POSTGRES_SCHEMA.split(";"):
                    if statement.strip():
                        self._execute(connection, statement)
                migrations = POSTGRES_MIGRATIONS
            else:
                connection.executescript(SCHEMA)
                migrations = MIGRATIONS
            for migration in migrations:
                try:
                    self._execute(connection, migration)
                except sqlite3.OperationalError as exc:
                    if (
                        not self.is_postgres
                        and "duplicate column name" not in str(exc).lower()
                    ):
                        raise

    def save_scan(self, result: dict[str, Any]) -> int:
        scanned_at = datetime.now(timezone.utc).isoformat()
        payload = {
            "findings": result.get("findings", []),
            "discovered_urls": result.get("discovered_urls", []),
            "severity": result.get("severity"),
            "risk_level": result.get("risk_level"),
        }
        with self._connect() as connection:
            query = """
                INSERT INTO scans
                    (target, final_url, scanned_at, status, score, summary,
                     response_status, response_size, results_json, error_message)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """
            if self.is_postgres:
                query += " RETURNING id"
            cursor = self._execute(
                connection,
                query,
                (
                    result["target"],
                    result.get("final_url"),
                    scanned_at,
                    result["status"],
                    result["score"],
                    result["summary"],
                    result.get("response_status"),
                    result.get("response_size"),
                    json.dumps(payload, ensure_ascii=False),
                    result.get("error_message"),
                ),
            )
            if self.is_postgres:
                return int(cursor.fetchone()["id"])
            return int(cursor.lastrowid)

    def get_scan(self, scan_id: str) -> dict[str, Any] | None:
        try:
            scan_id_int = int(scan_id)
        except (ValueError, OverflowError):
            return None
        try:
            with self._connect() as connection:
                row = self._execute(
                    connection, "SELECT * FROM scans WHERE id = ?", (scan_id_int,)
                ).fetchone()
        except OverflowError:
            return None
        if row is None:
            return None
        return self._row_to_dict(row)

    def fetch_recent_scans(self, limit: int = 10) -> list[dict[str, Any]]:
        with self._connect() as connection:
            rows = self._execute(
                connection,
                "SELECT * FROM scans ORDER BY scanned_at DESC LIMIT ?",
                (limit,),
            ).fetchall()
        return [self._row_to_dict(row) for row in rows]

    def save_report(self, scan_id: int, pdf: bytes) -> None:
        created_at = datetime.now(timezone.utc).isoformat()
        with self._connect() as connection:
            if self.is_postgres:
                self._execute(
                    connection,
                    """
                    INSERT INTO generated_reports (scan_id, pdf, created_at)
                    VALUES (?, ?, ?)
                    ON CONFLICT (scan_id) DO NOTHING
                    """,
                    (scan_id, pdf, created_at),
                )
            else:
                self._execute(
                    connection,
                    """
                    INSERT OR IGNORE INTO generated_reports (scan_id, pdf, created_at)
                    VALUES (?, ?, ?)
                    """,
                    (scan_id, sqlite3.Binary(pdf), created_at),
                )

    def get_report(self, scan_id: int) -> bytes | None:
        with self._connect() as connection:
            row = self._execute(
                connection,
                "SELECT pdf FROM generated_reports WHERE scan_id = ?",
                (scan_id,),
            ).fetchone()
        return bytes(row["pdf"]) if row is not None else None

    def create_user(
        self,
        name: str,
        email: str,
        password_hash: str,
        contact: str,
    ) -> int:
        created_at = datetime.now(timezone.utc).isoformat()
        with self._connect() as connection:
            query = """
                INSERT INTO users (name, email, password_hash, contact, created_at)
                VALUES (?, ?, ?, ?, ?)
            """
            if self.is_postgres:
                query += " RETURNING id"
            cursor = self._execute(
                connection,
                query,
                (name, email.lower(), password_hash, contact, created_at),
            )
            if self.is_postgres:
                return int(cursor.fetchone()["id"])
        return int(cursor.lastrowid)

    def get_user_by_email(self, email: str) -> dict[str, Any] | None:
        with self._connect() as connection:
            row = self._execute(
                connection, "SELECT * FROM users WHERE email = ?", (email.lower(),)
            ).fetchone()
        return dict(row) if row is not None else None

    def get_user(self, user_id: int) -> dict[str, Any] | None:
        with self._connect() as connection:
            row = self._execute(
                connection, "SELECT * FROM users WHERE id = ?", (user_id,)
            ).fetchone()
        return dict(row) if row is not None else None

    @staticmethod
    def _row_to_dict(row: sqlite3.Row) -> dict[str, Any]:
        data = dict(row)
        payload = json.loads(data.pop("results_json"))
        if isinstance(payload, dict):
            data["findings"] = payload.get("findings", [])
            data["discovered_urls"] = payload.get("discovered_urls", [])
            data["severity"] = payload.get("severity") or data.get("severity")
            data["risk_level"] = payload.get("risk_level") or data.get("risk_level")
        else:
            data["findings"] = payload
            data["discovered_urls"] = []
            data["severity"] = None
            data["risk_level"] = None
        return data


def initialize_database(database_path: str | Path) -> None:
    ScanStore(database_path)._initialize()


def get_db(database_path: str | Path) -> ScanStore:
    return ScanStore(database_path)
